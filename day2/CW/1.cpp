#include <bits/stdc++.h>
using namespace std;

int main()
{
    int a = 10;
    long long b = 10000000000;
    double c = 3.14159;
    char d = 'A';
    bool e = true;
    string f = "Hello, World!";

    cout << "Integer: " << a << endl;
    cout << "Long Long: " << b << endl;
    cout << "Double: " << c << endl;
    cout << "Character: " << d << endl;
    cout << "Boolean: " << e << endl;
    cout << "String: " << f << endl;
}