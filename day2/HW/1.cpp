#include <bits/stdc++.h>
using namespace std;

int main()
{
    cout << "Size of int: " << sizeof(int) << " bytes" << endl;
    cout << "Size of long long: " << sizeof(long long) << " bytes" << endl;
    cout << "Size of double: " << sizeof(double) << " bytes" << endl
            << "Size of char: " << sizeof(char) << " bytes" << endl;
}